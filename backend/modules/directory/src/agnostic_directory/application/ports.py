"""Ports of the directory module.

:class:`AccessRevoker` is implemented by the access module: when a group is deleted or a person is deprovisioned,
their role bindings go with them. :class:`GoogleDirectory` is the Google Workspace Admin SDK (read-only).
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime
from typing import Literal, Protocol

from agnostic_directory.domain.groups import Group, GroupMember, GroupSource, MemberRole
from agnostic_directory.domain.sync import (
    GoogleCredentials,
    GoogleRecord,
    MappingRule,
    ScimToken,
    ScimUser,
    SyncSettings,
    SyncState,
)
from agnostic_kernel.auth import Principal


class GroupRepository(Protocol):
    async def list(self) -> list[Group]: ...
    async def get(self, group_id: str) -> Group | None: ...
    async def find_external(self, source: GroupSource, external_id: str) -> Group | None: ...
    async def find_by_name(self, name: str) -> Group | None: ...
    async def add(self, group: Group) -> None: ...
    async def update(
        self,
        group_id: str,
        *,
        name: str | None = None,
        description: str | None = None,
        external_name: str | None = None,
    ) -> Group: ...
    async def delete(self, group_id: str) -> None: ...
    async def members(self, group_id: str) -> list[GroupMember]: ...
    async def groups_of(self, user_id: str) -> list[Group]: ...
    async def memberships_of(self, user_ids: Sequence[str]) -> dict[str, list[str]]:
        """User id → group ids, for many people at once (the members table)."""
        ...

    async def add_member(self, member: GroupMember) -> bool:
        """``False`` when they were already a member (the role is updated)."""
        ...

    async def remove_member(self, group_id: str, user_id: str) -> bool: ...
    async def remove_user(self, user_id: str) -> list[str]:
        """Remove someone from every group; returns the group ids they left."""
        ...

    async def set_role(self, group_id: str, user_id: str, role: MemberRole) -> None: ...
    async def list_by_source(self, source: GroupSource) -> list[Group]: ...
    async def rule_members(self) -> list[GroupMember]:
        """Every membership a mapping rule created."""
        ...

    async def add_rule_member(self, member: GroupMember) -> bool:
        """Add unless they already are a member (a manual membership or an owner role stays as it is)."""
        ...

    async def remove_rule_member(self, group_id: str, user_id: str) -> bool:
        """Remove a membership only if a mapping rule created it."""
        ...

    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...


class AccessRevoker(Protocol):
    async def revoke_principal(
        self, kind: Literal["user", "group"], principal_id: str, *, actor: Principal, reason: str
    ) -> int:
        """Delete every binding of the principal (audited, in the caller's transaction); returns how many."""
        ...


class ScimRepository(Protocol):
    async def tokens(self) -> list[ScimToken]: ...
    async def token(self, token_id: str) -> ScimToken | None: ...
    async def token_by_hash(self, token_hash: str) -> ScimToken | None: ...
    async def add_token(self, token: ScimToken) -> None: ...
    async def update_token(
        self,
        token_id: str,
        *,
        last_used_at: datetime | None = None,
        expires_at: datetime | None = None,
        revoked_at: datetime | None = None,
    ) -> None: ...
    async def state(self) -> SyncState: ...
    async def record_request(self, *, error: str | None = None, counts: dict[str, int] | None = None) -> None: ...
    async def save_counts(self, counts: dict[str, int]) -> None: ...
    async def counts(self) -> dict[str, int]: ...
    async def users(self) -> list[ScimUser]: ...
    async def user(self, user_id: str) -> ScimUser | None: ...
    async def user_by_name(self, user_name: str) -> ScimUser | None: ...
    async def user_by_external_id(self, external_id: str) -> ScimUser | None: ...
    async def save_user(self, user: ScimUser) -> None: ...
    async def delete_user(self, user_id: str) -> None: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...


class MappingRuleRepository(Protocol):
    async def list(self) -> list[MappingRule]: ...
    async def get(self, rule_id: str) -> MappingRule | None: ...
    async def add(self, rule: MappingRule) -> None: ...
    async def delete(self, rule_id: str) -> None: ...


class DirectoryConfigRepository(Protocol):
    async def settings(self) -> SyncSettings: ...
    async def save_settings(self, settings: SyncSettings) -> None: ...
    async def google(self) -> GoogleRecord: ...
    async def save_google(
        self,
        *,
        config_enc: str | None = None,
        group_filter: tuple[str, ...] | None = None,
        enabled: bool | None = None,
    ) -> None: ...
    async def record_google_run(self, *, error: str | None, counts: dict[str, int] | None) -> None: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...


@dataclass(frozen=True, slots=True)
class GoogleGroup:
    id: str
    email: str
    name: str


@dataclass(frozen=True, slots=True)
class GoogleUser:
    id: str
    primary_email: str
    name: str
    suspended: bool
    aliases: tuple[str, ...] = ()


class GoogleDirectoryError(Exception):
    """Google refused (bad key, missing delegation, wrong admin) or couldn't be reached; the message says which."""


class GoogleDirectory(Protocol):
    async def groups(self, credentials: GoogleCredentials) -> list[GoogleGroup]: ...
    async def member_emails(self, credentials: GoogleCredentials, group_id: str) -> list[str]:
        """Emails of the group's active user members, nested groups included."""
        ...

    async def users(self, credentials: GoogleCredentials) -> list[GoogleUser]: ...
    async def user(self, credentials: GoogleCredentials, key: str) -> GoogleUser: ...
