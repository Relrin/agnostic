import { assistantCalls, assistantHandlers, sampleOrgHandlers, renderPage } from "@agnostic/testing";
import { screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { setupServer } from "msw/node";
import { afterAll, afterEach, beforeAll, describe, expect, it } from "vitest";

import { AskPage } from "./ask-page";

let calls = assistantCalls();
const handlers = () => [...assistantHandlers(calls), ...sampleOrgHandlers()];
const server = setupServer(...handlers());

beforeAll(() => {
  server.listen({ onUnhandledFrame: "error" });
});
afterEach(() => {
  calls = assistantCalls();
  server.resetHandlers(...handlers());
});
afterAll(() => {
  server.close();
});

describe("AskPage", () => {
  it("shows a stored conversation with its generated, sourced answer", async () => {
    renderPage(AskPage, { path: "/i/$instance/ask", url: "/i/prod-agentos/ask?conversation=conv_1" });
    const messages = await screen.findByRole("list", { name: "Messages" });
    expect(within(messages).getByText("Why did daily-brief fail last night?")).toBeInTheDocument();
    const answer = within(messages).getByRole("article", { name: "Answer from Ask your OS" });
    expect(within(answer).getByText(/never reached/)).toBeInTheDocument();
    expect(within(answer).getByRole("link", { name: "Trace daily-brief · 9c1e7d40" })).toBeInTheDocument();
    expect(within(answer).getByText(/Generated by ollama:qwen3:8b/)).toBeInTheDocument();
    expect(screen.getByRole("button", { name: /^Why did daily-brief fail last night\?/ })).toHaveAttribute(
      "aria-current",
      "page",
    );
  });

  it("asks from the command palette's text with the page context", async () => {
    const user = userEvent.setup();
    renderPage(AskPage, {
      path: "/i/$instance/ask",
      url: "/i/prod-agentos/ask?q=What%20failed%20today%3F&context=trace:tr_9c1e7d40",
    });
    const box = await screen.findByLabelText("Ask your OS");
    expect(box).toHaveValue("What failed today?");
    const file = new File(["03:00:31 ERROR web_search timed out"], "run.log", { type: "text/plain" });
    await user.upload(screen.getAllByLabelText("Attach file")[0] as HTMLInputElement, file);
    expect(screen.getByRole("list", { name: "Attachments" })).toHaveTextContent("run.log");
    // jsdom's File can't go through undici's FormData; attachments are covered by the API tests.
    await user.click(screen.getByRole("button", { name: "Remove run.log" }));
    expect(screen.queryByRole("list", { name: "Attachments" })).not.toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Send" }));

    expect(await screen.findByText(/never reached/)).toBeInTheDocument();
    const sent = calls.questions[0];
    expect(sent?.get("question")).toBe("What failed today?");
    expect(sent?.get("context")).toBe("trace:tr_9c1e7d40");
    expect(sent?.get("files")).toBeNull();
  });

  it("says the feature is off instead of offering it", async () => {
    server.resetHandlers(...sampleOrgHandlers());
    renderPage(AskPage, { path: "/i/$instance/ask", url: "/i/prod-agentos/ask" });
    expect(await screen.findByText("Ask your OS is off")).toBeInTheDocument();
    expect(screen.queryByLabelText("Ask your OS")).not.toBeInTheDocument();
  });
});
