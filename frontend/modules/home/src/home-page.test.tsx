import {
  API,
  assistantCalls,
  assistantHandlers,
  GATEWAY,
  p01Handlers,
  p02Handlers,
  renderPage,
  sampleMe,
  sampleOrg,
  sampleOverview,
} from "@agnostic/testing";
import { screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { http, HttpResponse } from "msw";
import { setupServer } from "msw/node";
import { afterAll, afterEach, beforeAll, describe, expect, it } from "vitest";

import { HomePage, kpiDelta } from "./home-page";

const handlers = () => [...p01Handlers(), ...p02Handlers()];
const server = setupServer(...handlers());

beforeAll(() => {
  server.listen({ onUnhandledFrame: "error" });
});
afterEach(() => {
  server.resetHandlers(...handlers());
});
afterAll(() => {
  server.close();
});

describe("HomePage", () => {
  it("shows what needs attention, the KPIs and the primitives", async () => {
    renderPage(HomePage, { path: "/i/$instance/home", url: "/i/prod-agentos/home" });
    expect(await screen.findByText("3 approvals waiting")).toBeInTheDocument();
    expect(screen.getByText("daily-brief failed twice")).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Review" })).toHaveAttribute(
      "href",
      "/i/prod-agentos/approvals?tool=refund_customer",
    );
    expect(screen.getByText("6 agents · 3 agent teams · 5 workflows on prod-agentos")).toBeInTheDocument();

    const kpis = screen.getByRole("region", { name: "Key metrics, last 7 days" });
    expect(within(kpis).getByText("4,912")).toBeInTheDocument();
    expect(within(kpis).getByText("1.8%")).toBeInTheDocument();
    expect(within(kpis).getByText("6.4 s")).toBeInTheDocument();

    const primitives = screen.getByRole("table", { name: "Primitives" });
    expect(within(primitives).getByText("support-triage")).toBeInTheDocument();
    expect(within(primitives).getByText("+ v4 draft", { exact: false })).toBeInTheDocument();
    expect(screen.getByText("Maya Chen approved refund_customer on billing-agent")).toBeInTheDocument();
    // AI features are off: nothing on Home mentions them.
    expect(screen.queryByText("Ask your OS")).not.toBeInTheDocument();
  });

  it("asks your OS and streams the answer with its sources when AI features are on", async () => {
    const calls = assistantCalls();
    server.use(...assistantHandlers(calls));
    const user = userEvent.setup();
    renderPage(HomePage, { path: "/i/$instance/home", url: "/i/prod-agentos/home" });

    const box = await screen.findByLabelText("Ask your OS");
    // The failing schedule from "Needs attention" is the first suggestion; Tab takes it.
    expect(box).toHaveAttribute("placeholder", "Why did daily-brief fail last night?");
    await user.type(box, "Why did d");
    await user.keyboard("{Tab}");
    expect(box).toHaveValue("Why did daily-brief fail last night?");
    expect(screen.getByText(/Answers are generated on our own Ollama server/)).toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Send" }));

    const answer = await screen.findByRole("article", { name: "Answer from Ask your OS" });
    expect(await within(answer).findByText(/never reached/)).toBeInTheDocument();
    expect(within(answer).getByText("get_schedule_runs")).toBeInTheDocument();
    expect(within(answer).getByText("get_trace")).toBeInTheDocument();
    expect(within(answer).getByRole("link", { name: "Trace daily-brief · 9c1e7d40" })).toHaveAttribute(
      "href",
      "/i/prod-agentos/traces/tr_9c1e7d40",
    );
    expect(within(answer).getByText(/Generated by ollama:qwen3:8b/)).toBeInTheDocument();
    expect(calls.questions[0]?.get("question")).toBe("Why did daily-brief fail last night?");
    expect(calls.questions[0]?.get("context")).toBe("page:home");
    expect(screen.getByRole("link", { name: "Open conversation" })).toHaveAttribute(
      "href",
      "/i/prod-agentos/ask?conversation=conv_1",
    );
  });

  it("explains sections the viewer can't see and calm instances", async () => {
    server.use(
      http.get(`${API}/instances/:instance/overview`, () =>
        HttpResponse.json({
          ...sampleOverview,
          attention: [],
          activity: null,
          unavailable: { activity: "You don't have audit:read." },
        }),
      ),
    );
    renderPage(HomePage, { path: "/i/$instance/home", url: "/i/prod-agentos/home" });
    expect(await screen.findByText(/Nothing needs you right now/)).toBeInTheDocument();
    expect(screen.getByText("You don't have audit:read.")).toBeInTheDocument();
  });

  it("shows an error state with the request id", async () => {
    server.use(
      http.get(`${API}/instances/:instance/overview`, () =>
        HttpResponse.json(
          {
            type: "x",
            title: "Down",
            status: 502,
            code: "instance_unreachable",
            detail: "prod-agentos didn't answer",
            request_id: "req_1",
          },
          { status: 502 },
        ),
      ),
    );
    renderPage(HomePage, { path: "/i/$instance/home", url: "/i/prod-agentos/home" });
    expect(await screen.findByText("prod-agentos didn't answer")).toBeInTheDocument();
    expect(screen.getByText("Request id req_1")).toBeInTheDocument();
  });
});

describe("kpiDelta", () => {
  it("colours by good and bad, not by arrow direction", () => {
    expect(
      kpiDelta({ value: 10, previous: 8, delta: 2, delta_pct: 25 }, "count", " vs previous 7 days"),
    ).toEqual({
      label: "25%",
      direction: "up",
      sentiment: "good",
      context: " vs previous 7 days",
    });
    expect(
      kpiDelta({ value: 0.018, previous: 0.014, delta: 0.004, delta_pct: 28 }, "rate", ""),
    ).toMatchObject({
      label: "0.4 pt",
      sentiment: "bad",
    });
    expect(
      kpiDelta({ value: 6400, previous: 7200, delta: -800, delta_pct: -11 }, "latency", ""),
    ).toMatchObject({
      label: "800 ms",
      direction: "down",
      sentiment: "good",
    });
    expect(kpiDelta({ value: 1, previous: null, delta: null, delta_pct: null }, "count", "")).toBeUndefined();
  });
});

describe("GetStarted", () => {
  it("lists the first steps still to do, opens their tours and can be dismissed", async () => {
    let sent: unknown;
    server.use(
      http.get(`${API}/org`, () =>
        HttpResponse.json({ ...sampleOrg, member_count: 1, pending_invitations: 0 }),
      ),
      http.get(`${GATEWAY}/sessions`, () =>
        HttpResponse.json({ data: [], meta: { page: 1, limit: 1, total_pages: 0, total_count: 0 } }),
      ),
      http.patch(`${API}/me`, async ({ request }) => {
        sent = await request.json();
        return HttpResponse.json({ ...sampleMe, preferences: { "onboarding.dismissed": true } });
      }),
    );
    renderPage(HomePage, { path: "/i/$instance/home", url: "/i/prod-agentos/home" });

    const card = await screen.findByRole("region", { name: "Get started" });
    expect(within(card).getByText("1 of 3 done")).toBeInTheDocument();
    const steps = within(card).getByRole("list", { name: "First steps" });
    expect(
      within(steps).getByRole("heading", { name: /Connect your first instance\s*\(done\)/ }),
    ).toBeInTheDocument();
    expect(
      within(steps).getByRole("heading", { name: /Chat with your first agent\s*\(to do\)/ }),
    ).toBeInTheDocument();
    const [chatTour] = within(steps).getAllByRole("link", { name: "Show me" });
    expect(chatTour).toHaveAttribute("href", "/i/prod-agentos/chat?tour=chat");
    expect(within(steps).getByRole("link", { name: "Sign-in settings" })).toHaveAttribute(
      "href",
      "/org/settings/authentication",
    );

    await userEvent.setup().click(within(card).getByRole("button", { name: "Dismiss" }));
    await waitFor(() => {
      expect(screen.queryByRole("region", { name: "Get started" })).not.toBeInTheDocument();
    });
    expect(sent).toEqual({ preferences: { "onboarding.dismissed": true } });
  });
});
